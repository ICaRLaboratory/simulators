"""Rebuild compact Gen3 link-local CAD from the source checkout in NOTICE.md."""
import argparse
import base64
from pathlib import Path
import xml.etree.ElementTree as ET

import fast_simplification
import numpy as np

parser = argparse.ArgumentParser(__doc__)
parser.add_argument('kinova_dir', type=Path, help='GEN3_FOR_URDF_ARM_V11_MOD directory')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
urdf = ET.parse(args.kinova_dir / 'urdf/GEN3_FOR_URDF_ARM_V11_MOD.urdf')
rows = []
for link in urdf.findall('link'):
    name = link.attrib['name']
    path = args.kinova_dir / 'meshes' / (name + '.STL')
    records = np.fromfile(path, dtype=[('normal', '<f4', (3,)), ('v', '<f4', (3, 3)), ('attr', '<u2')], offset=84)
    verts, tri = np.unique(records['v'].reshape(-1, 3), axis=0, return_inverse=True)
    original = verts.astype('float64')
    original_tri = tri.reshape(-1, 3).astype('int32')
    # Some shells have narrow seams or ports: a fixed triangle budget can
    # displace their outer surface by several millimetres. Bound each extent.
    for budget in (3500, 5500, 8000, len(records)):
        if budget >= len(records):
            verts, tri = original, original_tri
            break
        verts, tri = fast_simplification.simplify(original, original_tri, target_count=budget)
        if max(np.abs(original.min(0)-verts.min(0)).max(), np.abs(original.max(0)-verts.max(0)).max()) < .0005:
            break
    xyz = np.rint(verts * 100000)
    assert np.abs(xyz).max() < 32768 and len(verts) < 65536
    def encode(a, dtype):
        return base64.b64encode(a.astype(dtype).tobytes()).decode('ascii')
    rows.append(f"  // {name}\n  ['{encode(xyz, '<i2')}', '{encode(tri, '<u2')}'],\n")
(root / 'assets/vendor/kinova/mesh-data.js').write_text('// Generated by scripts/build-gen3-meshes.py; see NOTICE.md and LICENSE.txt.\nexport default [\n' + ''.join(rows) + '];\n')
