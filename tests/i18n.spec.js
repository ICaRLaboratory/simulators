import {test, expect} from '@playwright/test';
const root=process.env.SIM_BASE || 'http://127.0.0.1:8765/simulators/';
const kinds=['cruise-control','dc-motor','ball-and-beam'];
test('locale toggle translates catalog, persists only language and synchronizes research URLs',async({page})=>{
 await page.goto(root);
 await expect(page.locator('html')).toHaveAttribute('lang','ko');
 await expect(page.locator('.sim-card')).toHaveCount(17);
 await page.evaluate(()=>{document.addEventListener('icar:lang',()=>{window.languageEventSeen=true;});});
 await page.locator('[data-lang="en"]').click();
 expect(await page.evaluate(()=>window.languageEventSeen)).toBe(true);
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await expect(page.locator('[data-lang="en"]')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('h1')).toHaveText('Adjust, observe, understand.');
 await expect(page.locator('[data-id="research-tracking"] [data-launch]')).toHaveAttribute('href','https://icarlaboratory.github.io/research.html?sim=track&lang=en#interactive');
 await page.locator('#search').fill('접촉');
 await expect(page.locator('[data-id="research-contact"]')).toBeVisible();
 await page.locator('#search').fill('contact');
 await expect(page.locator('[data-id="research-contact"]')).toBeVisible();
 expect(await page.evaluate(()=>Object.keys(localStorage))).toEqual(['icar-lang']);
 await page.goto(root+'?lang=ko');
 await expect(page.locator('html')).toHaveAttribute('lang','ko');
});
test('English-first restores Korean, and failure messages survive locale changes',async({page})=>{
 await page.goto(root+'ball-and-beam/?lang=en');
 await expect(page.locator('#kp-help')).toContainText('Responds');
 await page.locator('[data-lang="ko"]').click();
 await expect(page.locator('#kp-help')).toContainText('현재 오차');
 await expect(page.locator('summary')).toHaveText('모델·제어식');
 for(let i=0;i<10;i++)await page.locator('#disturb').click();
 await page.locator('#start-pause').click();
 await expect(page.locator('#start-pause')).toBeDisabled();
 await page.locator('[data-lang="en"]').click();
 await expect(page.locator('#simulation-message')).toContainText('The ball left the rail.');
 await expect(page.locator('#start-pause')).toBeDisabled();
 await page.locator('[data-lang="ko"]').click();
 await expect(page.locator('#simulation-message')).toContainText('공이 레일');
 await page.locator('#reset').click();
 await expect(page.locator('#start-pause')).toBeEnabled();
});
test('blocked language storage still allows explicit locale and toggling',async({page})=>{
 await page.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked');}});});
 await page.goto(root+'?lang=en');
 await expect(page.locator('h1')).toHaveText('Adjust, observe, understand.');
 await page.locator('[data-lang="ko"]').click();
 await expect(page.locator('h1')).toHaveText('조절하고, 관찰하고, 이해하다.');
});
for(const kind of kinds) test(`${kind}: language changes preserve running state, controls and translated accessible content`,async({page})=>{
 await page.goto(root+kind+'/?lang=ko');
 await page.locator('#kp').focus(); await page.keyboard.press('ArrowRight');
 const kp=await page.locator('#kp').inputValue();
 await page.locator('#start-pause').click(); await page.waitForTimeout(350);
 const before=Number(await page.locator('#sim-time').textContent());
 await page.locator('[data-lang="en"]').click();
 await expect(page.locator('#start-pause')).toHaveText('Pause');
 expect(Number(await page.locator('#sim-time').textContent())).toBeGreaterThanOrEqual(before);
 await expect(page.locator('#kp')).toHaveValue(kp);
 await page.locator('#start-pause').click();
 const snapshot=await page.locator('.metrics').innerText();
 const graph=await page.locator('#response').evaluate(canvas=>canvas.toDataURL());
 await page.locator('summary').click();
 const untranslated=await page.evaluate(()=>{const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);const a=[];while(w.nextNode()){const n=w.currentNode;if(!n.parentElement.closest('script,noscript,.language-switch')&&/[가-힣]/.test(n.nodeValue))a.push(n.nodeValue);}return a;});
 expect(untranslated).toEqual([]);
 expect(await page.locator('#apparatus').getAttribute('aria-label')).not.toMatch(/[가-힣]/);
 expect(await page.title()).not.toMatch(/[가-힣]/);
 await page.locator('[data-lang="ko"]').click(); await page.locator('[data-lang="en"]').click();
 expect(await page.locator('.metrics').innerText()).toBe(snapshot);
 expect(await page.locator('#response').evaluate(canvas=>canvas.toDataURL())).toBe(graph);
 expect(await page.locator('meta[name="description"]').getAttribute('content')).not.toMatch(/[가-힣]/);
 await expect(page.locator('details')).toHaveAttribute('open','');
 await page.locator('#disturb').click();
 expect(await page.locator('#simulation-message').innerText()).not.toMatch(/[가-힣]/);
 await page.locator('#reset').click();
 await expect(page.locator('#sim-time')).toHaveText('0.00');
 await expect(page.locator('#simulation-message')).toContainText('Reset');
});
